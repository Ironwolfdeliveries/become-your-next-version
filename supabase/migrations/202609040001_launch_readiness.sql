-- Launch readiness: private owner/admin authority, first-party analytics,
-- First Circle feedback, database hardening, and supporting indexes.

create table if not exists public.account_access (
  user_id uuid primary key references auth.users(id) on delete cascade,
  platform_role text not null default 'member' check (platform_role in ('member', 'admin', 'owner')),
  entitlement_tier text check (entitlement_tier in ('foundation', 'builder', 'architect', 'architect_coaching', 'graduate')),
  entitlement_status text not null default 'active' check (entitlement_status in ('active', 'paused')),
  reason text check (char_length(reason) <= 500),
  granted_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_audit_events (
  id uuid primary key default gen_random_uuid(),
  actor_user_id uuid not null references auth.users(id) on delete restrict,
  target_user_id uuid references auth.users(id) on delete set null,
  action text not null check (char_length(action) between 1 and 120),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  event_type text not null check (event_type in ('page_view','snapshot_start','snapshot_complete','signup_start','signup_complete','architect_assessment_start','architect_assessment_complete','blueprint_view','daily_active','membership_view','checkout_start','checkout_complete','cancellation','feedback_submit')),
  anonymous_id text check (anonymous_id is null or char_length(anonymous_id) between 10 and 80),
  user_id uuid references auth.users(id) on delete set null,
  route text not null check (char_length(route) between 1 and 300),
  metadata jsonb not null default '{}'::jsonb check (pg_column_size(metadata) <= 4096),
  created_at timestamptz not null default now()
);

create table if not exists public.first_circle_feedback (
  user_id uuid primary key references auth.users(id) on delete cascade,
  signup_easy integer check (signup_easy between 1 and 5),
  understood_bynv integer check (understood_bynv between 1 and 5),
  assessment_clear integer check (assessment_clear between 1 and 5),
  blueprint_useful integer check (blueprint_useful between 1 and 5),
  daily_direction_clear integer check (daily_direction_clear between 1 and 5),
  kai_helpful integer check (kai_helpful between 1 and 5),
  confused_by text check (char_length(confused_by) <= 3000),
  unnecessary text check (char_length(unnecessary) <= 3000),
  return_tomorrow text check (char_length(return_tomorrow) <= 3000),
  would_pay boolean,
  additional_feedback text check (char_length(additional_feedback) <= 5000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

