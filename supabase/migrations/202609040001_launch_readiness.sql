-- Keep privileged policy helpers outside the exposed API schema. Public wrappers
-- are invoker functions and disclose only a yes/no answer for the current JWT.
create schema if not exists private;
revoke all on schema private from public, anon;
grant usage on schema private to authenticated;

create or replace function private.is_community_admin()
returns boolean language sql security definer stable set search_path = '' as $$
  select exists (select 1 from public.community_entitlements where user_id = (select auth.uid()) and community_role = 'admin')
$$;
create or replace function private.is_community_moderator()
returns boolean language sql security definer stable set search_path = '' as $$
  select exists (select 1 from public.community_entitlements where user_id = (select auth.uid()) and community_role in ('moderator', 'admin'))
$$;
create or replace function private.is_community_restricted(target_user_id uuid)
returns boolean language sql security definer stable set search_path = '' as $$
  select exists (select 1 from public.community_member_restrictions where user_id = target_user_id and (restricted_until is null or restricted_until > now()))
$$;
create or replace function private.can_access_community_room(target_room_id uuid)
returns boolean language sql security definer stable set search_path = '' as $$
  select exists (
    select 1 from public.community_rooms room
    left join public.community_entitlements entitlement on entitlement.user_id = (select auth.uid())
    where room.id = target_room_id and room.active
      and (
        room.access_level = 'community'
        or (room.access_level = 'first_circle' and coalesce(entitlement.first_circle, false))
        or (room.access_level = 'priority' and coalesce(entitlement.access_level, 'community') in ('priority', 'mastermind'))
        or (room.access_level = 'mastermind' and coalesce(entitlement.access_level, 'community') = 'mastermind')
      )
  )
$$;

revoke all on all functions in schema private from public, anon;
grant execute on function private.is_community_admin(), private.is_community_moderator(), private.is_community_restricted(uuid), private.can_access_community_room(uuid) to authenticated;

